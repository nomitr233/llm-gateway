import type { PoolClient } from "pg";

/**
 * 表结构靠两条线维持：
 *   SCHEMA_SQL  —— 基线，全部幂等 DDL，新库一次建齐
 *   MIGRATIONS  —— 已有库的增量变更，只跑还没记录在 schema_version 里的
 */
export const SCHEMA_VERSION = 3;

export const SCHEMA_SQL = `
create table if not exists schema_version (
    version integer primary key,
    applied_at timestamptz not null default now()
);

create table if not exists providers (
    id integer generated by default as identity primary key,
    name text not null unique,
    kind text not null default 'openai',
    base_url text not null,
    api_key_ciphertext text not null,
    timeout_ms integer not null default 120000,
    enabled boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists models (
    id integer generated by default as identity primary key,
    provider_id integer not null references providers (id) on delete cascade,
    public_name text not null unique,
    upstream_model text not null,
    category text not null check (category in ('text', 'image', 'video', 'jev')),
    is_default boolean not null default false,
    enabled boolean not null default true,
    created_at timestamptz not null default now()
);

create unique index if not exists models_one_default_per_category
    on models (category) where is_default;

create table if not exists services (
    id integer generated by default as identity primary key,
    name text not null unique,
    key_hash text not null unique,
    key_preview text not null,
    enabled boolean not null default true,
    created_at timestamptz not null default now()
);
`;

interface Migration {
    version: number;
    sql: string;
}

const MIGRATIONS: Migration[] = [
    {
        // v2：加上语音类别
        version: 2,
        sql: `
            alter table models drop constraint if exists models_category_check;
            alter table models add constraint models_category_check
                check (category in ('text', 'image', 'video', 'jev', 'audio'));
        `,
    },
    {
        // v3：语音拆成 tts / asr 两个方向，端点才能校验方向
        version: 3,
        sql: `
            alter table models drop constraint if exists models_category_check;
            update models set category = 'tts' where category = 'audio';
            alter table models add constraint models_category_check
                check (category in ('text', 'image', 'video', 'jev', 'tts', 'asr'));
        `,
    },
];

export async function applySchema(client: PoolClient): Promise<void> {
    await client.query("begin");
    try {
        await client.query(SCHEMA_SQL);

        const result = await client.query<{ version: number | null }>("select max(version) as version from schema_version");
        const applied = result.rows[0]?.version ?? 0;
        if (applied === 0) {
            // 空库：SCHEMA_SQL 已经是最终形态，直接把基线版本记上
            await client.query("insert into schema_version (version) values ($1) on conflict (version) do nothing", [1]);
        }

        for (const migration of MIGRATIONS) {
            if (migration.version <= applied) continue;
            await client.query(migration.sql);
            await client.query("insert into schema_version (version) values ($1) on conflict (version) do nothing", [
                migration.version,
            ]);
        }

        await client.query("commit");
    } catch (error) {
        await client.query("rollback").catch(() => {});
        throw error;
    }
}
